import 'package:flutter/foundation.dart';

/// Represents a single telemetry GPS sample captured by the foreground tracking service.
///
/// Adheres strictly to PRD F4 and business rules BR-8, BR-9, BR-10.
@immutable
class LocationPoint {
  const LocationPoint({
    required this.id,
    required this.sessionId,
    required this.latitude,
    required this.longitude,
    required this.accuracy,
    required this.recordedAt,
    this.speed,
    this.heading,
    this.altitude,
    this.batteryLevel,
    this.isMock = false,
  });

  /// Unique client-generated UUID for idempotent batch synchronization.
  final String id;

  /// Foreign key referencing the active duty session.
  final String sessionId;

  /// WGS84 Latitude.
  final double latitude;

  /// WGS84 Longitude.
  final double longitude;

  /// Horizontal accuracy radius in meters.
  final double accuracy;

  /// Device timestamp in UTC.
  final DateTime recordedAt;

  /// Speed in meters per second (null if unavailable).
  final double? speed;

  /// Compass bearing in degrees (0.0 to 360.0).
  final double? heading;

  /// Altitude in meters above sea level.
  final double? altitude;

  /// Battery percentage integer (0 to 100).
  final int? batteryLevel;

  /// Whether the location was generated by a mock provider (PRD BR-9).
  final bool isMock;

  LocationPoint copyWith({
    String? id,
    String? sessionId,
    double? latitude,
    double? longitude,
    double? accuracy,
    DateTime? recordedAt,
    double? speed,
    double? heading,
    double? altitude,
    int? batteryLevel,
    bool? isMock,
  }) {
    return LocationPoint(
      id: id ?? this.id,
      sessionId: sessionId ?? this.sessionId,
      latitude: latitude ?? this.latitude,
      longitude: longitude ?? this.longitude,
      accuracy: accuracy ?? this.accuracy,
      recordedAt: recordedAt ?? this.recordedAt,
      speed: speed ?? this.speed,
      heading: heading ?? this.heading,
      altitude: altitude ?? this.altitude,
      batteryLevel: batteryLevel ?? this.batteryLevel,
      isMock: isMock ?? this.isMock,
    );
  }

  /// The row sent to `location_points`. Only columns that exist there: the
  /// sync flag is device-local bookkeeping and must not be sent, and the owner
  /// is set by the server.
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'session_id': sessionId,
      'latitude': latitude,
      'longitude': longitude,
      'accuracy': accuracy,
      'speed': speed,
      'heading': heading,
      'altitude': altitude,
      'battery_level': batteryLevel,
      'is_mock': isMock,
      'recorded_at': recordedAt.toUtc().toIso8601String(),
    };
  }

  factory LocationPoint.fromJson(Map<String, dynamic> json) {
    return LocationPoint(
      id: json['id'] as String,
      sessionId: json['session_id'] as String,
      latitude: (json['latitude'] as num).toDouble(),
      longitude: (json['longitude'] as num).toDouble(),
      accuracy: (json['accuracy'] as num).toDouble(),
      recordedAt: DateTime.parse(json['recorded_at'] as String).toUtc(),
      speed: (json['speed'] as num?)?.toDouble(),
      heading: (json['heading'] as num?)?.toDouble(),
      altitude: (json['altitude'] as num?)?.toDouble(),
      batteryLevel: json['battery_level'] as int?,
      isMock: json['is_mock'] as bool? ?? false,
    );
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is LocationPoint &&
          runtimeType == other.runtimeType &&
          id == other.id &&
          sessionId == other.sessionId &&
          latitude == other.latitude &&
          longitude == other.longitude &&
          accuracy == other.accuracy &&
          recordedAt == other.recordedAt &&
          isMock == other.isMock;

  @override
  int get hashCode =>
      id.hashCode ^
      sessionId.hashCode ^
      latitude.hashCode ^
      longitude.hashCode ^
      accuracy.hashCode ^
      recordedAt.hashCode ^
      isMock.hashCode;
}
